"""Joins the project files into one main.py that can be pasted into a QuantConnect project.

The modules stay the source of truth; this only concatenates them in dependency
order, drops the imports between them and makes ``core.`` resolve to the
bundle itself.

    python scripts/bundle.py [output]   # default: dist/main.py
"""
import re
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent / "TopologicalAlpha"
ORDER = ["core", "universe", "alpha", "portfolio", "risk", "execution", "main"]
LOCAL = "|".join(ORDER)
DROP = re.compile(
    rf"^(# (end)?region.*|from AlgorithmImports import \*|from __future__ import annotations"
    rf"|import (math|numpy as np|pandas as pd)|import ({LOCAL})|from ({LOCAL}) import .*)$"
)

HEADER = '''"""Topological alpha, single-file build of the topological-alpha project.

Generated by scripts/bundle.py from the project modules; edit those, not this file.
"""
from __future__ import annotations

# region imports
from AlgorithmImports import *
import math
import sys
import numpy as np
import pandas as pd
# endregion
'''


def strip(source: str) -> str:
    lines = [line for line in source.splitlines() if not DROP.match(line.strip())]
    return "\n".join(lines).strip("\n")


def main() -> None:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else PROJECT.parent / "dist" / "main.py"
    parts = [HEADER]
    for name in ORDER:
        body = strip((PROJECT / f"{name}.py").read_text())
        parts.append(f"\n# {'-' * 30} {name}.py {'-' * 30}\n\n{body}\n")
        if name == "core":
            parts.append("\n# the other parts call these as core.<name>\ncore = sys.modules[__name__]\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(parts))
    print(output)


if __name__ == "__main__":
    main()
